CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE proveedores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    direccion TEXT
);

CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    edad INT,
    rtn VARCHAR(20)
);

CREATE TABLE productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    precio NUMERIC(10, 2) NOT NULL,
    stock INT NOT NULL DEFAULT 0,
    id_categoria BIGINT REFERENCES categorias(id) ON DELETE SET NULL
);

CREATE TABLE facturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    id_cliente BIGINT REFERENCES clientes(id) ON DELETE CASCADE
);

CREATE TABLE detalle_factura (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad INT NOT NULL DEFAULT 1,
    id_factura BIGINT REFERENCES facturas(id) ON DELETE CASCADE,
    id_producto BIGINT REFERENCES productos(id) ON DELETE RESTRICT
);

CREATE TABLE producto_proveedor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT REFERENCES productos(id) ON DELETE CASCADE,
    id_proveedor BIGINT REFERENCES proveedores(id) ON DELETE CASCADE
);
